// check-a11y-routes.mjs: unit tests for the required-route coverage logic in
// templates/a11y/check.mjs (parseRequiredRoutes and uncoveredRoutes).
//
// Runs on any Node, no Docker and no browser:
//
//   node tests/check-a11y-routes.mjs
//
// Exits 0 when every assertion holds, non-zero on the first failure.

import assert from "node:assert/strict";
import { parseRequiredRoutes, uncoveredRoutes } from "../templates/a11y/check.mjs";

// parseRequiredRoutes: one route per line, normalized like a page, deduped in
// order. Blank lines and lines starting with # are ignored.
assert.deepEqual(parseRequiredRoutes(""), []);
assert.deepEqual(parseRequiredRoutes("\n   \n# generated by the app's router\n"), []);
assert.deepEqual(parseRequiredRoutes("/\ndocs/\n/docs\n"), ["", "docs"]);
assert.deepEqual(parseRequiredRoutes("docs"), ["docs"]);
assert.deepEqual(parseRequiredRoutes("/about\r\n  /about\n"), ["about"]);
assert.deepEqual(parseRequiredRoutes("api/users\napi/users/{id}\n"), ["api/users", "api/users/{id}"]);
assert.throws(() => parseRequiredRoutes("../etc"), /climb out of the site root/);

// uncoveredRoutes: a route counts as covered when it equals a resolved page,
// or when a resolved page is its index.html form (/docs/ is covered by
// docs/index.html, / by index.html).
assert.deepEqual(uncoveredRoutes(["", "docs"], ["index.html", "docs/index.html"]), []);
assert.deepEqual(uncoveredRoutes(["", "docs", "about"], ["index.html", "docs/page.html"]), ["docs", "about"]);
assert.deepEqual(uncoveredRoutes(["about.html"], ["about.html"]), []);
assert.deepEqual(uncoveredRoutes(["about"], ["about.html"]), ["about"]);
assert.deepEqual(uncoveredRoutes(["docs"], ["docs/"]), []);
assert.deepEqual(uncoveredRoutes([""], ["index.html"]), []);
assert.deepEqual(uncoveredRoutes([""], ["docs/index.html"]), [""]);
assert.deepEqual(uncoveredRoutes([], ["index.html"]), []);

console.log("check-a11y-routes: ok");
